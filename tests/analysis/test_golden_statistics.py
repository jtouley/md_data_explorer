"""Golden known-answer tests for the statistics behind every claim.

Each test runs a compute_* function on a committed synthetic cohort (tests/fixtures/synthetic,
generated by scripts/make_synthetic_data.py) and checks the result against an independent
calculation done directly with scipy / statsmodels / lifelines on numpy arrays, plus the
effect the generator planted. If a refactor changes which test runs, how missing data is
handled, how codes are decoded, or what level is modelled as the event, these fail.

Test name follows: test_unit_scenario_expectedBehavior
"""

from __future__ import annotations

import math

import numpy as np
import polars as pl
import pytest
import statsmodels.api as sm
from lifelines import KaplanMeierFitter
from lifelines.statistics import logrank_test
from scipy import stats
from statsmodels.stats.weightstats import CompareMeans, DescrStatsW

from clinical_analytics.analysis.compute import (
    compute_comparison_analysis,
    compute_count_analysis,
    compute_predictor_analysis,
    compute_survival_analysis,
)
from clinical_analytics.core.analysis_types import AnalysisContext
from clinical_analytics.core.result_presentation import present_analysis
from clinical_analytics.datasets.demo import get_demo_csv_path

DEXA = "DEXA result 1: Normal 2: Osteopenia 3: Osteoporosis"
STATIN = "Statin use 1: Yes 2: No"

REL = 1e-9


def _context(**fields: object) -> AnalysisContext:
    context = AnalysisContext()
    for name, value in fields.items():
        setattr(context, name, value)
    return context


def _group_values(df: pl.DataFrame, value_col: str, group_col: str, group: str) -> np.ndarray:
    return (
        df.filter(pl.col(group_col) == group)
        .select(pl.col(value_col).drop_nulls().cast(pl.Float64))
        .to_series()
        .to_numpy()
    )


def _logit_reference(y: np.ndarray, columns: list[np.ndarray]) -> sm.regression.linear_model.RegressionResults:
    design = sm.add_constant(np.column_stack(columns))
    return sm.Logit(y, design).fit(disp=0)


class TestGoldenComparison:
    def test_compare_ldlByTreatment_matchesWelchReferenceAndRecoversPlantedEffect(self, load_synthetic_dataset):
        # Arrange
        df = load_synthetic_dataset("cohort")
        drug = _group_values(df, "ldl", "treatment", "drug")
        placebo = _group_values(df, "ldl", "treatment", "placebo")
        ref_t, ref_p = stats.ttest_ind(drug, placebo, equal_var=False)
        ref_lo, ref_hi = CompareMeans(DescrStatsW(drug), DescrStatsW(placebo)).tconfint_diff(usevar="unequal")
        n_missing = df["ldl"].null_count()

        # Act
        result = compute_comparison_analysis(df, _context(primary_variable="ldl", grouping_variable="treatment"))

        # Assert: same test, same numbers as the reference
        assert result["test_type"] == "welch_t_test"
        assert result["statistic"] == pytest.approx(ref_t, rel=REL)
        assert result["p_value"] == pytest.approx(ref_p, rel=REL)
        assert result["mean_diff"] == pytest.approx(drug.mean() - placebo.mean(), rel=REL)
        assert (result["ci_lower"], result["ci_upper"]) == pytest.approx((ref_lo, ref_hi), rel=REL)
        # Assert: missing outcomes excluded and counted
        assert n_missing > 0
        assert result["n_excluded"] == n_missing
        assert result["n_used"] == df.height - n_missing
        # Assert: the generator lowered LDL by 18 on drug; the CI must cover it
        assert result["ci_lower"] < -18.0 < result["ci_upper"]

    def test_compare_unequalVarianceSmallGroup_usesWelchNotPooled(self, load_synthetic_dataset):
        # Arrange
        df = load_synthetic_dataset("unequal_groups")
        common = _group_values(df, "sbp", "arm", "common")
        rare = _group_values(df, "sbp", "arm", "rare")
        _, welch_p = stats.ttest_ind(common, rare, equal_var=False)
        _, pooled_p = stats.ttest_ind(common, rare, equal_var=True)

        # Act
        result = compute_comparison_analysis(df, _context(primary_variable="sbp", grouping_variable="arm"))

        # Assert
        assert result["group_sizes"] == {"common": 40, "rare": 5}
        assert result["p_value"] == pytest.approx(welch_p, rel=REL)
        assert not math.isclose(result["p_value"], pooled_p, rel_tol=0.01)
        assert result["df"] < 10  # Welch-Satterthwaite df driven by the n=5, high-variance arm

    def test_compare_sparse2x2_usesFisherExactWithPlantedTable(self, load_synthetic_dataset):
        # Arrange: generator wrote exposed 3/4 infected, unexposed 1/16 infected
        df = load_synthetic_dataset("sparse_cells")
        planted = np.array([[15, 1], [1, 3]])  # rows: infection 0,1; columns: exposed no, yes
        ref_or, ref_p = stats.fisher_exact(planted)

        # Act
        result = compute_comparison_analysis(df, _context(primary_variable="infection", grouping_variable="exposed"))

        # Assert
        assert result["test_type"] == "fisher_exact"
        assert result["min_expected_count"] < 5
        assert result["p_value"] == pytest.approx(ref_p, rel=REL)
        assert result["odds_ratio"] == pytest.approx(ref_or, rel=REL)
        assert result["event_level"] == "1"
        assert result["group_proportions"] == pytest.approx({"no": 1 / 16, "yes": 3 / 4}, rel=REL)

    def test_compare_codedDexaByTreatment_isCategoricalChiSquare(self, load_synthetic_dataset):
        # Arrange
        df = load_synthetic_dataset("cohort")
        table = np.array(
            [
                [df.filter((pl.col(DEXA) == code) & (pl.col("treatment") == arm)).height for arm in ["drug", "placebo"]]
                for code in [1, 2, 3]
            ]
        )
        ref_chi2, ref_p, ref_dof, _ = stats.chi2_contingency(table)

        # Act
        result = compute_comparison_analysis(df, _context(primary_variable=DEXA, grouping_variable="treatment"))

        # Assert: a 1/2/3 code is not averaged as if it were a measurement
        assert result["outcome_kind"] == "categorical"
        assert result["test_type"] == "chi_square"
        assert result["chi2"] == pytest.approx(ref_chi2, rel=REL)
        assert result["p_value"] == pytest.approx(ref_p, rel=REL)
        assert result["dof"] == ref_dof == 2

    def test_compare_oneTwoCodedStatinByDiabetes_reportsProportionOfYes(self, load_synthetic_dataset):
        # Arrange: statin is coded 1=Yes 2=No; the event must be "Yes", not the larger code
        df = load_synthetic_dataset("cohort")
        expected = {
            str(flag): df.filter(pl.col("diabetes") == flag)[STATIN].eq(1).mean() for flag in df["diabetes"].unique()
        }

        # Act
        result = compute_comparison_analysis(df, _context(primary_variable=STATIN, grouping_variable="diabetes"))

        # Assert
        assert result["outcome_kind"] == "binary"
        assert result["event_level"] == "1"
        assert result["group_proportions"] == pytest.approx(expected, rel=REL)
        # Generator: statin probability 0.35 without diabetes, 0.65 with
        assert result["group_proportions"]["1"] > result["group_proportions"]["0"]

    def test_compare_ldlBySite_matchesOneWayAnovaReference(self, load_synthetic_dataset):
        # Arrange: three sites, LDL shifted by 0 / +4 / +9 in the generator
        df = load_synthetic_dataset("cohort")
        sites = ["North", "South", "West"]
        ref_f, ref_p = stats.f_oneway(*[_group_values(df, "ldl", "site", site) for site in sites])
        ref_means = {site: float(_group_values(df, "ldl", "site", site).mean()) for site in sites}

        # Act
        result = compute_comparison_analysis(df, _context(primary_variable="ldl", grouping_variable="site"))

        # Assert
        assert result["test_type"] == "anova"
        assert result["statistic"] == pytest.approx(ref_f, rel=REL)
        assert result["p_value"] == pytest.approx(ref_p, rel=REL)
        assert result["group_means"] == pytest.approx(ref_means, rel=REL)
        assert result["n_excluded"] == df["ldl"].null_count()
        assert ref_means["North"] < ref_means["South"] < ref_means["West"]

    def test_compare_demoOutcomeByHypertension_matchesContingencyReference(self):
        # Arrange: the bundled "Load sample" cohort (shipped in the package, same generator)
        df = pl.read_csv(get_demo_csv_path())
        counts = df.group_by("outcome", "hypertension").len()
        table = np.array(
            [
                [counts.filter((pl.col("outcome") == y) & (pl.col("hypertension") == g))["len"].sum() for g in (0, 1)]
                for y in (0, 1)
            ]
        )
        ref_chi2, ref_p, ref_dof, ref_expected = stats.chi2_contingency(table)
        ref_props = {str(g): table[1, j] / table[:, j].sum() for j, g in enumerate((0, 1))}

        # Act
        result = compute_comparison_analysis(df, _context(primary_variable="outcome", grouping_variable="hypertension"))

        # Assert: expected counts are all >= 5, so chi-square (Yates-corrected for 2x2), not Fisher
        assert ref_expected.min() >= 5
        assert result["test_type"] == "chi_square"
        assert result["chi2"] == pytest.approx(ref_chi2, rel=REL)
        assert result["p_value"] == pytest.approx(ref_p, rel=REL)
        assert result["dof"] == ref_dof == 1
        assert result["group_proportions"] == pytest.approx(ref_props, rel=REL)
        assert result["n_used"] == df.height == 80


class TestGoldenPredictor:
    def test_predict_outcomeFromAgeTreatmentDiabetes_matchesLogitReference(self, load_synthetic_dataset):
        # Arrange
        df = load_synthetic_dataset("cohort")
        reference = _logit_reference(
            df["outcome"].to_numpy(),
            [
                df["age"].to_numpy(),
                df["diabetes"].to_numpy(),
                (df["treatment"] == "placebo").cast(pl.Int64).to_numpy(),
            ],
        )
        ref_or = np.exp(reference.params)
        ref_ci = np.exp(reference.conf_int())
        context = _context(primary_variable="outcome", predictor_variables=["age", "diabetes", "treatment"])

        # Act
        result = compute_predictor_analysis(df, context)

        # Assert: identical model to an independent statsmodels fit
        summary = result["summary"]
        for i, term in enumerate(["age", "diabetes", "treatment_placebo"], start=1):
            assert summary[term]["Odds Ratio"] == pytest.approx(ref_or[i], rel=1e-6)
            assert summary[term]["CI Lower"] == pytest.approx(ref_ci[i, 0], rel=1e-6)
            assert summary[term]["CI Upper"] == pytest.approx(ref_ci[i, 1], rel=1e-6)
            assert summary[term]["P-Value"] == pytest.approx(reference.pvalues[i], rel=1e-6)
        assert result["n_used"] == df.height
        assert result["event_level"] == "1"
        # Assert: planted log-odds age +0.06/yr, placebo +0.9 vs drug fall in the 95% CIs
        assert summary["age"]["CI Lower"] < math.exp(0.06) < summary["age"]["CI Upper"]
        assert summary["treatment_placebo"]["CI Lower"] < math.exp(0.9) < summary["treatment_placebo"]["CI Upper"]

    def test_predict_oneTwoCodedOutcome_modelsYesAsEvent(self, load_synthetic_dataset):
        # Arrange: fitting raw 1/2 codes would invert or break the model; Yes (1) is the event
        df = load_synthetic_dataset("cohort")
        reference = _logit_reference(df[STATIN].eq(1).cast(pl.Int64).to_numpy(), [df["diabetes"].to_numpy()])

        # Act
        result = compute_predictor_analysis(df, _context(primary_variable=STATIN, predictor_variables=["diabetes"]))

        # Assert
        assert result["event_level"] == "1"
        assert result["summary"]["diabetes"]["Odds Ratio"] == pytest.approx(np.exp(reference.params[1]), rel=1e-6)
        assert result["summary"]["diabetes"]["Odds Ratio"] > 1

    def test_predict_codedCategoricalPredictor_entersAsIndicators(self, load_synthetic_dataset):
        # Arrange
        df = load_synthetic_dataset("cohort")
        dexa = df[DEXA].to_numpy()
        reference = _logit_reference(df["outcome"].to_numpy(), [(dexa == 2).astype(int), (dexa == 3).astype(int)])

        # Act
        result = compute_predictor_analysis(df, _context(primary_variable="outcome", predictor_variables=[DEXA]))

        # Assert: one odds ratio per non-reference level, not one per "unit of code"
        terms = sorted(k for k in result["summary"] if k != "Intercept")
        assert terms == [f"{DEXA}_2", f"{DEXA}_3"]
        assert result["summary"][f"{DEXA}_3"]["Odds Ratio"] == pytest.approx(np.exp(reference.params[2]), rel=1e-6)

    def test_predict_perfectSeparation_refusesWithReason(self, load_synthetic_dataset):
        # Arrange
        df = load_synthetic_dataset("separation")

        # Act
        result = compute_predictor_analysis(df, _context(primary_variable="relapse", predictor_variables=["marker"]))

        # Assert
        assert "summary" not in result
        assert "separation" in result["error"]


class TestGoldenSurvival:
    def test_survival_byTreatment_matchesLifelinesAndPlantedHazard(self, load_synthetic_dataset):
        # Arrange
        df = load_synthetic_dataset("cohort")
        arms = {
            arm: (_group_values(df, "followup_days", "treatment", arm), _group_values(df, "event", "treatment", arm))
            for arm in ["drug", "placebo"]
        }
        (drug_t, drug_e), (placebo_t, placebo_e) = arms["drug"], arms["placebo"]
        ref = logrank_test(drug_t, placebo_t, event_observed_A=drug_e, event_observed_B=placebo_e)
        ref_medians = {arm: KaplanMeierFitter().fit(t, e).median_survival_time_ for arm, (t, e) in arms.items()}
        context = _context(time_variable="followup_days", event_variable="event", grouping_variable="treatment")

        # Act
        result = compute_survival_analysis(df, context)

        # Assert
        assert result["n_used"] == df.height
        assert result["group_sizes"] == {arm: len(t) for arm, (t, _) in arms.items()}
        assert result["logrank_p_value"] == pytest.approx(ref.p_value, rel=REL)
        for arm, median in ref_medians.items():
            expected = None if np.isinf(median) else pytest.approx(float(median), rel=REL)
            assert result["group_medians"][arm] == expected
        # Generator: drug multiplies the hazard by exp(-0.5) (about 0.61)
        assert result["logrank_p_value"] < 0.05


