#!/usr/bin/env python3
"""Write the example data contract for the synthetic cohort.

tests/fixtures/synthetic/contracts/cohort.odcs.yaml is generated by the same builder the upload
path uses, from tests/fixtures/synthetic/cohort.csv, with a fixed timestamp so it is
reproducible. It is tagged ``synthetic``; scripts/check_no_data_files.py rejects any tracked
contract that records a source-file hash without that tag. A test fails if the committed file
drifts from what the builder produces.

Run from the repo root:  uv run python scripts/make_synthetic_contract.py
"""

from __future__ import annotations

import hashlib
from datetime import UTC, datetime
from pathlib import Path

import polars as pl

from clinical_analytics.contracts.builder import ContractInputs, build_contract
from clinical_analytics.storage.versioning import compute_dataset_version

SYNTHETIC_DIR = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "synthetic"
COHORT_CSV = SYNTHETIC_DIR / "cohort.csv"
CONTRACT_PATH = SYNTHETIC_DIR / "contracts" / "cohort.odcs.yaml"
HEADER = (
    "# ODCS v3.2.0 contract for the SYNTHETIC fixture tests/fixtures/synthetic/cohort.csv.\n"
    "# Generated by scripts/make_synthetic_contract.py; do not edit by hand.\n"
    "# Contracts for real uploads live in <data home>/data/contracts/ and never enter git.\n"
)


def synthetic_contract_yaml() -> str:
    df = pl.read_csv(COHORT_CSV)
    inputs = ContractInputs(
        upload_id="cohort-synthetic",
        dataset_version=compute_dataset_version([df]),
        dataset_name="Synthetic cardiometabolic cohort",
        id_column="patient_id",
        source_file_sha256=hashlib.sha256(COHORT_CSV.read_bytes()).hexdigest(),
        tags=("synthetic",),
        created_at=datetime(2026, 11, 3, tzinfo=UTC),
    )
    return HEADER + build_contract(df, inputs).to_yaml()


def main() -> None:
    CONTRACT_PATH.parent.mkdir(parents=True, exist_ok=True)
    CONTRACT_PATH.write_text(synthetic_contract_yaml(), encoding="utf-8")
    print(f"Wrote {CONTRACT_PATH.relative_to(SYNTHETIC_DIR.parents[2])}")


if __name__ == "__main__":
    main()
